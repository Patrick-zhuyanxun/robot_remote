"""Set up dual_arm_rig_v2.usda for the box task (see a box, move it to the table centre, open its 4 flaps).
Edits the USD in place and is safe to re-run (also after the rig is regenerated by build_usda.py):

  ~/isaac-sim-6.1/python.sh robot_remote/dual_arm_sim/setup_box_task_scene.py [--cam-tilt-deg 0]

1. Wrist camera mounts: xeg32_camera_mount_link had mass 1e-9 kg on a free revolute camera_tilt_joint
   (stiffness 0, damping 0), so the camera swung with every arm motion. Now 0.05 kg with a sane inertia and
   a stiff position drive holding the tilt at --cam-tilt-deg (default 0). Still a revolute joint (keeps the
   DOF list; the real mount is adjustable).
2. Box body: kinematic (fixed in place, the arms cannot push or drag it; user decision 2026-10-19), cardboard /
   table friction. Only the four flaps move.
3. Flaps: the two long (major) flaps plus two new short (minor) flaps on the end walls. Minor flaps lie
   below the major ones (1 mm gap), like a real box: open the major flaps first. Each hinge: closed = joint
   limit 0 (cannot fall into the box), fully open = 175 deg (folded back outward; PhysX revolute limits beyond
   +-180 deg misbehave), light damping, no spring: short of vertical a released flap falls back closed, pushed
   past vertical it falls open.
"""

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
p.add_argument("--usd", type=Path, default=HERE / "dual_arm_rig_v2.usda")
p.add_argument("--cam-tilt-deg", type=float, default=0.0, help="wrist camera tilt held by the drive [deg]")
args, _ = p.parse_known_args()

from isaacsim import SimulationApp  # noqa: E402  (pxr is only importable inside Kit)

app = SimulationApp({"headless": True})

from pxr import Gf, PhysxSchema, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade  # noqa: E402

stage = Usd.Stage.Open(str(args.usd))
BOX = "/World/CardboardBox"
BODY = f"{BOX}/Body"

# ---------------------------------------------------------------- parameters (all SI; angular drive per degree)
CAM_MASS, CAM_INERTIA = 0.05, (3e-5, 3e-5, 3e-5)          # small wrist camera + bracket
CAM_STIFFNESS, CAM_DAMPING = 20.0, 1.0                      # N m / deg, N m s / deg (rigid-looking, implicit)
BOX_MASS = 0.4                                              # empty 32 x 45 x 25 cm corrugated box
MAJOR_MASS, MINOR_MASS = 0.035, 0.02                        # 5 mm board, ~0.5 kg / m^2
HINGE_DAMPING = 0.0002                                      # N m s / deg (~0.011 per rad): a released flap settles in ~1-3 s
OPEN_LIMIT = 175.0                                          # deg from closed (PhysX clamps revolute limits to +-180)
CARDBOARD = dict(static=0.6, dynamic=0.5, restitution=0.0)
TABLE = dict(static=0.5, dynamic=0.4, restitution=0.0)
RIGID = dict(maxDepenetrationVelocity=0.5, maxLinearVelocity=2.0, linearDamping=0.1, angularDamping=0.5,
             solverPositionIterationCount=16, solverVelocityIterationCount=4)

# Box geometry in the Body frame (from the USD): walls 6 mm, outer x +-0.16, y +-0.225, top z +0.125.
MINOR_W, MINOR_D, T = 0.30, 0.12, 0.005                     # minor flap width (x) / depth (y) / thickness
LIFT = 0.006                                                # major flaps raised onto the minor ones (+1 mm gap)


def physics_material(name, f):
    path = f"/World/Looks/Physics/{name}"
    mat = UsdShade.Material.Define(stage, path)
    api = UsdPhysics.MaterialAPI.Apply(mat.GetPrim())
    api.CreateStaticFrictionAttr(f["static"])
    api.CreateDynamicFrictionAttr(f["dynamic"])
    api.CreateRestitutionAttr(f["restitution"])
    PhysxSchema.PhysxMaterialAPI.Apply(mat.GetPrim()).CreateFrictionCombineModeAttr("average")
    return mat


def bind_physics(prim, mat):
    UsdShade.MaterialBindingAPI.Apply(prim).Bind(mat, UsdShade.Tokens.weakerThanDescendants, "physics")


def rigid_settings(prim, mass):
    UsdPhysics.MassAPI.Apply(prim).CreateMassAttr(mass)
    rb = PhysxSchema.PhysxRigidBodyAPI.Apply(prim)
    for k, v in RIGID.items():
        getattr(rb, f"Create{k[0].upper()}{k[1:]}Attr")(v)
    rb.CreateEnableCCDAttr(True)


def flap(name, center, scale, mass, color=(0.62, 0.42, 0.2)):
    cube = UsdGeom.Cube.Define(stage, f"{BOX}/{name}")
    prim = cube.GetPrim()
    cube.CreateSizeAttr(1.0)
    cube.CreateExtentAttr([(-0.5, -0.5, -0.5), (0.5, 0.5, 0.5)])
    cube.CreateDisplayColorAttr([color])
    xf = UsdGeom.Xformable(prim)
    xf.ClearXformOpOrder()
    xf.AddTranslateOp(UsdGeom.XformOp.PrecisionDouble).Set(Gf.Vec3d(*center))
    xf.AddOrientOp(UsdGeom.XformOp.PrecisionDouble).Set(Gf.Quatd(1, 0, 0, 0))
    xf.AddScaleOp(UsdGeom.XformOp.PrecisionDouble).Set(Gf.Vec3d(*scale))
    UsdPhysics.RigidBodyAPI.Apply(prim)
    UsdPhysics.CollisionAPI.Apply(prim)
    UsdShade.MaterialBindingAPI.Apply(prim).Bind(UsdShade.Material(stage.GetPrimAtPath("/World/Looks/cardboard")))
    rigid_settings(prim, mass)
    return prim


def hinge(name, flap_name, axis, pos0, pos1, lower, upper):
    """Body -> flap revolute joint; joint frames aligned with both bodies, so angle 0 = closed (as authored)."""
    j = UsdPhysics.RevoluteJoint.Define(stage, f"{BOX}/{name}")
    j.CreateAxisAttr(axis)
    j.CreateBody0Rel().SetTargets([Sdf.Path(BODY)])
    j.CreateBody1Rel().SetTargets([Sdf.Path(f"{BOX}/{flap_name}")])
    j.CreateLocalPos0Attr(Gf.Vec3f(*pos0))
    j.CreateLocalPos1Attr(Gf.Vec3f(*pos1))
    j.CreateLocalRot0Attr(Gf.Quatf(1, 0, 0, 0))
    j.CreateLocalRot1Attr(Gf.Quatf(1, 0, 0, 0))
    j.CreateLowerLimitAttr(lower)
    j.CreateUpperLimitAttr(upper)
    drive = UsdPhysics.DriveAPI.Apply(j.GetPrim(), "angular")
    drive.CreateTypeAttr("force")
    drive.CreateStiffnessAttr(0.0)
    drive.CreateDampingAttr(HINGE_DAMPING)


# ---------------------------------------------------------------- 1. wrist cameras
for side in ("left", "right"):
    mount = next(pr for pr in stage.Traverse()
                 if pr.GetName() == "xeg32_camera_mount_link" and pr.HasAPI(UsdPhysics.RigidBodyAPI)
                 and f"/arm_{side}/" in str(pr.GetPath()))
    m = UsdPhysics.MassAPI.Apply(mount)
    m.CreateMassAttr(CAM_MASS)
    m.CreateDiagonalInertiaAttr(Gf.Vec3f(*CAM_INERTIA))
    joint = stage.GetPrimAtPath(f"/World/dual_arm_rig/Joints/arm_{side}_xeg32_camera_tilt_joint")
    if not joint.IsValid():
        joint = next(pr for pr in stage.Traverse() if pr.GetName() == f"arm_{side}_xeg32_camera_tilt_joint")
    d = UsdPhysics.DriveAPI.Apply(joint, "angular")
    d.CreateStiffnessAttr(CAM_STIFFNESS)
    d.CreateDampingAttr(CAM_DAMPING)
    d.CreateTargetPositionAttr(args.cam_tilt_deg)
    print(f"[scene] {side} wrist camera: mount {CAM_MASS} kg, tilt drive k={CAM_STIFFNESS} c={CAM_DAMPING} "
          f"target {args.cam_tilt_deg} deg ({joint.GetPath()})", flush=True)

# ---------------------------------------------------------------- 2. box body + materials
cardboard_phys, table_phys = physics_material("cardboard", CARDBOARD), physics_material("table", TABLE)
for leg in ("top", "leg_0", "leg_1", "leg_2", "leg_3"):
    bind_physics(stage.GetPrimAtPath(f"/World/table/{leg}"), table_phys)
body = stage.GetPrimAtPath(BODY)
UsdPhysics.RigidBodyAPI(body).CreateKinematicEnabledAttr(True)   # was dynamic 0.4 kg: it got dragged along by the arm
rigid_settings(body, BOX_MASS)  # mass only matters if the body is made dynamic again
bind_physics(body, cardboard_phys)

# ---------------------------------------------------------------- 3. four flaps (Box frame = Body + (0.4, 0, 0.125))
BX, BZ = 0.4, 0.125
top = BZ + 0.125                                            # top edge of the walls in the box frame
major_z = top + LIFT + T / 2
minor_z = top + T / 2
# major (long) flaps: hinge on the long walls (Body x = +-0.16), axis Y; 0.157 wide, full 0.45 length
flap("LidBack", (BX + 0.0815, 0, major_z), (0.157, 0.45, T), MAJOR_MASS)
flap("LidFront", (BX - 0.0815, 0, major_z), (0.157, 0.45, T), MAJOR_MASS)
# minor (short) flaps: hinge on the end walls (Body y = +-0.225), axis X
flap("LidLeft", (BX, 0.225 - MINOR_D / 2, minor_z), (MINOR_W, MINOR_D, T), MINOR_MASS, (0.58, 0.39, 0.18))
flap("LidRight", (BX, -0.225 + MINOR_D / 2, minor_z), (MINOR_W, MINOR_D, T), MINOR_MASS, (0.58, 0.39, 0.18))
# Opening direction by the right-hand rule (free edge goes up first). Checked in the sim, see AGENTS.md.
hinge("LidBackJoint", "LidBack", "Y", (0.16, 0, 0.125 + LIFT), (0.5, 0, -0.5), 0.0, OPEN_LIMIT)
hinge("LidFrontJoint", "LidFront", "Y", (-0.16, 0, 0.125 + LIFT), (-0.5, 0, -0.5), -OPEN_LIMIT, 0.0)
hinge("LidLeftJoint", "LidLeft", "X", (0, 0.225, 0.125), (0, 0.5, -0.5), -OPEN_LIMIT, 0.0)
hinge("LidRightJoint", "LidRight", "X", (0, -0.225, 0.125), (0, -0.5, -0.5), 0.0, OPEN_LIMIT)
for name in ("LidBack", "LidFront", "LidLeft", "LidRight"):
    bind_physics(stage.GetPrimAtPath(f"{BOX}/{name}"), cardboard_phys)

stage.GetRootLayer().Save()
print(f"[scene] saved {args.usd.name}: box fixed (kinematic), 4 flaps, materials, wrist cameras", flush=True)
app.close()
